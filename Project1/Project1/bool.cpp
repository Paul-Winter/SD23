#include <iostream>
using namespace std;

int main() {

	// bool - Булевское (логическое) значение - правда (true/1) или ложь (false/0)
	bool a = true;
	bool b = false;
	bool c = 1;
	bool d = 0;
	bool e = 4;
	bool f = -1;
	bool g = 'a';
	bool h = "asdf";
	bool i = 5.2;
	bool j = '\0';

	cout << "a = " << a << '\n';
	cout << "b = " << b << '\n';
	cout << "c = " << c << '\n';
	cout << "d = " << d << '\n';
	cout << "e = " << e << '\n';
	cout << "f = " << f << '\n';
	cout << "g = " << g << '\n';
	cout << "h = " << h << '\n';
	cout << "i = " << i << '\n';
	cout << "j = " << j << '\n';

	return 0;
}